    sg = segment.num(segment.init==i);
    if node.isroot(i)
        Aeq(eqCount,i) = 1;   beq(eqCount) = Pin; % Set pressure in root node as known
        eqCount = eqCount + 1;
    elseif node.isterminal(i)==1       % Equation on terminal nodes
        Aeq(eqCount,i) = 1;   Aeq(eqCount,end) = -1;  Aeq(eqCount,Co+in) = - Xr.P(j,1:Nin);   
        Aeq(eqCount,Cv+out) = Xr.P(j,Nin+1:Nin+Nout);    
        Aeq(eqCount,Co+lsg) = Aeq(eqCount,Co+lsg) - prm.mu/prm.gamma;   % pressure drop estimation on terminal nodes
