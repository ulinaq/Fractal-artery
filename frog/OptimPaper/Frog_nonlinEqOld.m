        Junc = 1; Elas = 1;
    case 2  % Elasticity  
        Junc = 0; Elas = 1;
    case 3  % Junction
        Junc = 1; Elas = 0;
    case 4
        Junc = 0; Elas = 0;
       
end

Pin = prm.Pin; Pout = prm.Pout;
Co = node.n + vnode.n; Cv = Co+segment.n;
eqCount = 1; j=1; k=1;
