                + Xr.Pext(k,Nin+1:Nin+Nout)*x(Cv+out))/(prm.ha*prm.E))^(-4*Elas);
            eqCount = eqCount + 1; k=k+1;
        end
    else % no junction
        F{eqCount} = @(x) x(node.n+segint) - x(node.n+segend) + 8*prm.mu*vsegment.len(i)*x(Cv+i)/(pi*vsegment.rad(i)^4)...
